export type UIKey = keyof typeof UI.en

export function useUI() {
  const { language, resolveString } = useLanguage()
  const dict = UI[language] ?? UI.en
  const ui = (key: UIKey) => dict[key] ?? UI.en[key]
  return { ui, lang: language, r: resolveString }
}
